#!/usr/bin/env python3
"""Pool all glueball runs per coupling, compute GEVP 0++ masses and Creutz ratios, and compare the
dimensionless lattice gap a*m(beta) with two-loop asymptotic scaling a*Lambda_L(beta) (conjecture G2
of docs/01: m/Lambda_L should approach a positive constant as beta -> infinity).

Usage:  python scripts/glueball_summary.py ../results --md ../results/glueball-su2.md --png ../results/glueball-su2.png
Runs are grouped by (group, beta, lattice shape, smearing levels) from all *.npz files that are not
checkpoints.
"""
import argparse
import glob
import os
import sys
from collections import defaultdict

import numpy as np

from ymlattice import exact
from ymlattice.analysis import best_creutz, creutz_ratios, effective_masses, load_runs
from ymlattice.stats import binned_mean_err


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("resultsdir")
    ap.add_argument("--md", required=True)
    ap.add_argument("--png", default=None)
    ap.add_argument("--nblocks", type=int, default=20)
    args = ap.parse_args()

    groups = defaultdict(list)
    for p in sorted(glob.glob(os.path.join(args.resultsdir, "gb_*.npz"))):
        if p.endswith(".ckpt.npz"):
            continue
        d = np.load(p, allow_pickle=True)
        k = (str(d["group"]), float(d["beta"]), tuple(int(x) for x in d["shape"]), tuple(int(x) for x in d["levels"]))
        groups[k].append(p)

    rows = []
    for (group, beta, shape, levels), paths in sorted(groups.items(), key=lambda kv: kv[0][1]):
        (_, _, _, _), O, plaq, poly, W, sizes = load_runs(paths)
        N = 2 if group == "su2" else 3
        pm, pe = binned_mean_err(plaq, args.nblocks)
        em = effective_masses(O, 0, args.nblocks)
        mg, mge = em["gevp"]
        chis, nW = creutz_ratios(W, args.nblocks)
        Rmax = best_creutz(chis)
        aL = exact.a_lambda_lattice(beta, N)
        rows.append(dict(group=group, beta=beta, shape=shape, n=sum(sizes), runs=len(sizes), plaq=(pm, pe),
                         m=[(mg[t], mge[t]) for t in range(min(4, len(mg)))], chi=chis.get(Rmax) if Rmax else None,
                         Rmax=Rmax, aL=aL, nW=nW, poly=float(np.mean(poly.real))))

    out = []
    w = out.append
    w("# SU(2) 0++ glueball mass versus asymptotic scaling")
    w("")
    w("Generated by `lattice/scripts/glueball_summary.py` from the raw runs in `results/` (raw `.npz` files are not "
      "committed; rerun `lattice/scripts/glueball.py` with the parameters in `results/logs/*.log` to regenerate them).")
    w("")
    w("Method: zero-momentum time-slice sums of spatial plaquettes at several APE-smearing levels; connected "
      "correlation matrix; generalised eigenvalue problem with tau0 = 0; effective mass from the cosh form; block "
      "jackknife errors. By reflection positivity, effective masses decrease towards the true gap, so each value is "
      "an estimate of an upper bound on the gap a*m; tau = 1 is the first value not dominated by contact terms.")
    w("")
    w("| beta | lattice | meas. (runs) | plaquette | a m_eff(tau=0) | a m_eff(tau=1) | a m_eff(tau=2) | chi(R,R), largest R with <10% error | a Lambda_L (2-loop) | m/Lambda_L (tau=1) |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        sh = r["shape"]
        lat = f"{sh[1]}^3 x {sh[0]}"
        ms = [f"{v:.3f} +- {e:.3f}" if np.isfinite(v) and np.isfinite(e) else "-" for v, e in r["m"]]
        ms += ["-"] * (3 - len(ms))
        chi = f"{r['chi'][0]:.4f} +- {r['chi'][1]:.4f} (R={r['Rmax']})" if r["chi"] else "-"
        m1, e1 = r["m"][1] if len(r["m"]) > 1 else (np.nan, np.nan)
        ratio = f"{m1/r['aL']:.0f} +- {e1/r['aL']:.0f}" if np.isfinite(m1) else "-"
        w(f"| {r['beta']} | {lat} | {r['n']} ({r['runs']}) | {r['plaq'][0]:.5f} +- {r['plaq'][1]:.5f} | {ms[0]} | {ms[1]} | {ms[2]} | {chi} | {r['aL']:.3e} | {ratio} |")
    w("")
    if len(rows) >= 2:
        w("Asymptotic scaling test (conjecture G2 in lattice form): if the continuum limit has a mass gap, "
          "a*m(beta)/a*Lambda_L(beta) tends to a positive constant as beta grows. The Wilson action is known to "
          "approach asymptotic scaling slowly (ratios of physical quantities scale much earlier than either quantity "
          "matches the two-loop formula), so moderate drifts of m/Lambda_L at these couplings are expected.")
    text = "\n".join(out)
    with open(args.md, "w") as fh:
        fh.write(text + "\n")
    print(text)

    if args.png and rows:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(6.5, 4.2))
        b = np.array([r["beta"] for r in rows])
        m1 = np.array([r["m"][1][0] if len(r["m"]) > 1 else np.nan for r in rows])
        e1 = np.array([r["m"][1][1] if len(r["m"]) > 1 else np.nan for r in rows])
        ax.errorbar(b, m1, yerr=e1, fmt="o", color="k", label="0++ GEVP effective mass, tau=1 (this work)")
        good = np.isfinite(m1) & np.isfinite(e1) & (e1 > 0)
        if good.sum() >= 1:
            aL = np.array([r["aL"] for r in rows])
            wts = 1 / (e1[good] / aL[good]) ** 2
            C = np.sum(wts * m1[good] / aL[good]) / np.sum(wts)
            bb = np.linspace(b.min() - 0.1, b.max() + 0.2, 200)
            ax.plot(bb, [C * exact.a_lambda_lattice(x, 2) for x in bb], "-", color="#27c",
                    label=f"two-loop asymptotic scaling, m = {C:.0f} Lambda_L (weighted fit)")
        ax.set_yscale("log")
        ax.set_xlabel(r"$\beta = 4/g^2$")
        ax.set_ylabel(r"$a\,m_{0^{++}}$")
        ax.set_title("SU(2): lattice mass gap vs asymptotic scaling")
        ax.grid(alpha=0.3, which="both")
        ax.legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(args.png, dpi=150)
        print("wrote", args.png)


if __name__ == "__main__":
    sys.exit(main())
