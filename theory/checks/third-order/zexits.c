/* Section 16 of Part IV: Z_{n,k}, the junctions with two front-pairs p = (bd q, s-1) and p' with |p'| = k >= 5 and n plaquettes: zexit_count_n.py in C.
 * Usage: zexits D NMAX            (build: cc -O2 -o zexits zexits.c)
 *
 * As in zexit_count_n.py: the front of p' lies in G = bd q u E(P) (Lemma mg:lem:twofront(i)), and every plaquette of P is joined to V(q) by a chain
 * of plaquettes of P sharing vertices. The sets P with this property are the connected sets containing the root in the graph whose nodes are a root
 * (standing for V(q)) and the plaquettes, two plaquettes being adjacent when they share a vertex and a plaquette being adjacent to the root when it
 * has a vertex in V(q); they are generated by Redelmeier's method, each exactly once. For each P, the fronts in G with at least five edges are found
 * by a decision search restricted to G (each front once, from its smallest edge), and the conditions of Lemma mg:lem:junction are checked: every link
 * of G lies in at least two of bd q, the front and the plaquettes of P; the front shares a vertex with P; bd q shares a vertex with a marker; the
 * markers (link-components of P), bd q and the front are connected under "common vertex". A front vertex-disjoint from bd q can be p' in either
 * layer (fronts of one layer are vertex-disjoint) and counts twice; a front meeting V(q) counts once (the other layer). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int D, NMAX, R, W, NO;
static long stride[4], NVERT, NPLAQ, ORIG;
static int oi[6], oj[6];
static long long Z[16][64];
static long nsets;

static inline void plinks(long P, long *L) {
    long v = P / NO; int o = P % NO, i = oi[o], j = oj[o];
    L[0] = v * D + i; L[1] = (v + stride[i]) * D + j; L[2] = (v + stride[j]) * D + i; L[3] = v * D + j;
}
static inline void pverts(long P, long *V) {
    long v = P / NO; int o = P % NO, i = oi[o], j = oj[o];
    V[0] = v; V[1] = v + stride[i]; V[2] = v + stride[j]; V[3] = v + stride[i] + stride[j];
}
static int plaqs_at(long v, long *out) {
    int c = 0;
    for (int o = 0; o < NO; o++) for (int si = 0; si < 2; si++) for (int sj = 0; sj < 2; sj++)
        out[c++] = (v - si * stride[oi[o]] - sj * stride[oj[o]]) * NO + o;
    return c;
}
static inline long lend(long L, int e) { long v = L / D; return e ? v + stride[L % D] : v; }

/* ---------- the current set P ---------- */
static long Pl[16]; static int nP;
static long qL[4], qV[4];

/* ---------- fronts in G ---------- */
static long G[128]; static int nG;
static int inG(long L) { for (int a = 0; a < nG; a++) if (G[a] == L) return a; return -1; }
static char gS[128], gX[128];       /* edge status by index in G */
static long gv[256]; static int gdeg[256], gdec[256], ngv;   /* vertices touched */
static int vidx(long v) { for (int a = 0; a < ngv; a++) if (gv[a] == v) return a; gv[ngv] = v; gdeg[ngv] = 0; gdec[ngv] = 0; return ngv++; }
static int e0idx, nS;
static void check_front(void);
static void frec(int vi) {
    long v = gv[vi];
    int U[16], nu = 0;
    for (int a = e0idx; a < nG; a++) if (!gS[a] && !gX[a] && (lend(G[a], 0) == v || lend(G[a], 1) == v)) U[nu++] = a;
    for (int mask = 0; mask < (1 << nu); mask++) {
        int r = __builtin_popcount(mask);
        if (gdeg[vi] + r < 2) continue;
        int ngv0 = ngv;
        for (int a = 0; a < nu; a++) {
            if (mask >> a & 1) { gS[U[a]] = 1; nS++; long w = lend(G[U[a]], 0) == v ? lend(G[U[a]], 1) : lend(G[U[a]], 0); int wi = vidx(w); gdeg[vi]++; gdeg[wi]++; }
            else gX[U[a]] = 1;
        }
        gdec[vi] = 1;
        int nxt = -1;
        for (int a = 0; a < ngv; a++) if (gdeg[a] >= 1 && !gdec[a]) { if (nxt < 0 || (gdeg[a] == 1 && gdeg[nxt] != 1) || (((gdeg[a] == 1) == (gdeg[nxt] == 1)) && gv[a] < gv[nxt])) nxt = a; }
        if (nxt < 0) check_front(); else frec(nxt);
        gdec[vi] = 0;
        for (int a = nu - 1; a >= 0; a--) {
            if (mask >> a & 1) { gS[U[a]] = 0; nS--; long w = lend(G[U[a]], 0) == v ? lend(G[U[a]], 1) : lend(G[U[a]], 0); int wi = vidx(w); gdeg[vi]--; gdeg[wi]--; }
            else gX[U[a]] = 0;
        }
        ngv = ngv0;
    }
}
static int pi_[128], inphi[128];
static void check_front(void) {
    if (nS < 5) return;
    /* coverage */
    for (int a = 0; a < nG; a++) if (inphi[a] + gS[a] + pi_[a] < 2) return;
    /* the front's vertices */
    long VS[128]; int nvs = 0;
    for (int a = 0; a < nG; a++) if (gS[a]) for (int e = 0; e < 2; e++) {
        long w = lend(G[a], e); int seen = 0; for (int b = 0; b < nvs; b++) if (VS[b] == w) { seen = 1; break; }
        if (!seen) VS[nvs++] = w;
    }
    long VP[64]; int nvp = 0;
    for (int a = 0; a < nP; a++) { long V[4]; pverts(Pl[a], V); for (int c = 0; c < 4; c++) VP[nvp++] = V[c]; }
    int touchP = 0;
    for (int a = 0; a < nvs && !touchP; a++) for (int b = 0; b < nvp; b++) if (VS[a] == VP[b]) { touchP = 1; break; }
    if (!touchP) return;
    /* nodes: plaquettes (joined by shared links into markers), q, the front; join by shared vertices */
    int N = nP + 2, par[32];
    for (int a = 0; a < N; a++) par[a] = a;
    #define FIND(x) ({ int _x = (x); while (par[_x] != _x) { par[_x] = par[par[_x]]; _x = par[_x]; } _x; })
    for (int a = 0; a < nP; a++) for (int c = a + 1; c < nP; c++) {
        long Va[4], Vc[4]; pverts(Pl[a], Va); pverts(Pl[c], Vc); int sh = 0;
        for (int x = 0; x < 4 && !sh; x++) for (int y = 0; y < 4; y++) if (Va[x] == Vc[y]) { sh = 1; break; }
        if (sh) par[FIND(a)] = FIND(c);
    }
    int touchq = 0;   /* bd q must touch a marker */
    for (int a = 0; a < nP; a++) {
        long V[4]; pverts(Pl[a], V); int sh = 0;
        for (int x = 0; x < 4 && !sh; x++) for (int y = 0; y < 4; y++) if (V[x] == qV[y]) { sh = 1; break; }
        if (sh) { par[FIND(a)] = FIND(nP); touchq = 1; }
    }
    if (!touchq) return;
    int qS = 0;
    for (int x = 0; x < nvs && !qS; x++) for (int y = 0; y < 4; y++) if (VS[x] == qV[y]) { qS = 1; break; }
    if (qS) par[FIND(nP)] = FIND(nP + 1);
    for (int a = 0; a < nP; a++) {
        long V[4]; pverts(Pl[a], V); int sh = 0;
        for (int x = 0; x < 4 && !sh; x++) for (int y = 0; y < nvs; y++) if (V[x] == VS[y]) { sh = 1; break; }
        if (sh) par[FIND(a)] = FIND(nP + 1);
    }
    int r0 = FIND(0);
    for (int a = 1; a < N; a++) if (FIND(a) != r0) return;
    #undef FIND
    Z[nP][nS] += qS ? 1 : 2;
}
static int cmpl(const void *a, const void *b) { long x = *(const long *)a, y = *(const long *)b; return (x > y) - (x < y); }
static void process_P(void) {
    nsets++;
    /* G = bd q u E(P), sorted, with the coverage of each link by bd q and by P */
    nG = 0;
    for (int a = 0; a < 4; a++) G[nG++] = qL[a];
    for (int a = 0; a < nP; a++) { long L[4]; plinks(Pl[a], L); for (int c = 0; c < 4; c++) G[nG++] = L[c]; }
    qsort(G, nG, sizeof(long), cmpl);
    int m = 0; for (int a = 0; a < nG; a++) if (a == 0 || G[a] != G[a - 1]) G[m++] = G[a]; nG = m;
    for (int a = 0; a < nG; a++) { inphi[a] = 0; pi_[a] = 0; gS[a] = 0; gX[a] = 0; for (int c = 0; c < 4; c++) if (qL[c] == G[a]) inphi[a] = 1; }
    for (int a = 0; a < nP; a++) { long L[4]; plinks(Pl[a], L); for (int c = 0; c < 4; c++) pi_[inG(L[c])]++; }
    /* fronts in G, each from its smallest edge */
    for (e0idx = 0; e0idx < nG; e0idx++) {
        ngv = 0; nS = 1; gS[e0idx] = 1;
        int a0 = vidx(lend(G[e0idx], 0)), a1 = vidx(lend(G[e0idx], 1)); gdeg[a0] = 1; gdeg[a1] = 1;
        frec(a0);
        gS[e0idx] = 0; nS = 0;
        for (int a = 0; a < nG; a++) gX[a] = 0;
    }
}

/* ---------- Redelmeier enumeration of the sets P ---------- */
static char *reached, *inPf;
static void redel(long *untried, int nunt) {
    long mine[1024];
    memcpy(mine, untried, nunt * sizeof(long));
    for (int a = 0; a < nunt; a++) {
        long c = mine[a];
        Pl[nP++] = c; inPf[c] = 1;
        if (nP >= 3 || nP >= 1) process_P();
        if (nP < NMAX) {
            /* new neighbours of c (plaquettes sharing a vertex with c), not yet reached */
            long nb[64]; int nn = 0;
            long V[4]; pverts(c, V);
            for (int x = 0; x < 4; x++) { long ps[32]; int k = plaqs_at(V[x], ps); for (int y = 0; y < k; y++) if (!reached[ps[y]]) { reached[ps[y]] = 1; nb[nn++] = ps[y]; } }
            /* the untried set for the extension: the remaining mine[a+1..] plus the new neighbours */
            long nu[1024]; int nnu = 0;
            for (int b = a + 1; b < nunt; b++) nu[nnu++] = mine[b];
            for (int b = 0; b < nn; b++) nu[nnu++] = nb[b];
            redel(nu, nnu);
            for (int b = 0; b < nn; b++) reached[nb[b]] = 0;
        }
        nP--; inPf[c] = 0;
    }
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s D NMAX\n", argv[0]); return 1; }
    D = atoi(argv[1]); NMAX = atoi(argv[2]);
    NO = 0; for (int i = 0; i < D; i++) for (int j = i + 1; j < D; j++) { oi[NO] = i; oj[NO] = j; NO++; }
    R = 2 * NMAX + 6; W = 2 * R + 1;
    NVERT = 1; for (int i = 0; i < D; i++) { stride[i] = NVERT; NVERT *= W; }
    NPLAQ = NVERT * NO;
    ORIG = 0; for (int i = 0; i < D; i++) ORIG += (long)R * stride[i];
    reached = calloc(NPLAQ, 1); inPf = calloc(NPLAQ, 1);
    long q = ORIG * NO + 0;   /* orientation 0 = (0,1) */
    plinks(q, qL); pverts(q, qV);
    /* the root's neighbours: plaquettes with a vertex in V(q) */
    long start[256]; int ns = 0;
    for (int x = 0; x < 4; x++) { long ps[32]; int k = plaqs_at(qV[x], ps); for (int y = 0; y < k; y++) if (!reached[ps[y]]) { reached[ps[y]] = 1; start[ns++] = ps[y]; } }
    nP = 0;
    redel(start, ns);
    printf("D=%d, NMAX=%d: %ld sets P\n", D, NMAX, nsets);
    for (int n = 1; n <= NMAX; n++) {
        printf("Z_(%d,k), k >= 5:", n);
        for (int k = 5; k < 64; k++) if (Z[n][k]) printf(" %d:%lld", k, Z[n][k]);
        printf("\n");
    }
    return 0;
}
