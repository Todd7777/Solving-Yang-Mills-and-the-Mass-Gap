# Section 16 of Part IV (Remark mg:rem:practical): exact N^v_k for the effective constants. Usage: python3 fronts_count.py D KMAX
"""N^v_k: the number of fronts (connected edge sets of Z^D in which every vertex has degree >= 2) with k edges through the origin.
Fronts with k edges are found among the connected edge sets (bond animals) through the origin, generated by Redelmeier's method
(every connected set containing a fixed root edge exactly once); a front through the origin contains one of the 2D edges at the origin,
so we root at each such edge e and keep the fronts whose smallest edge at the origin is e (each front counted once).
Results: D=2, k<=9: {4: 4, 6: 12, 7: 12, 8: 70, 9: 160} (2 min); D=3, k<=8: {4: 12, 6: 132, 7: 108, 8: 2034} (15 min).
By hand, for D=3: 2034 = 1656 eight-cycles + 210 figure-eights (two plaquettes sharing exactly one vertex: 30 per vertex, 7 vertices each)
+ 168 theta graphs with paths of lengths 2, 2, 4 (8 per plaquette, 3 plaquettes per site, 7 vertices each); for D=2, 70 = 56 + 14 + 0."""
import sys
from collections import Counter
D = int(sys.argv[1]); KMAX = int(sys.argv[2])
E = [tuple(1 if k == i else 0 for k in range(D)) for i in range(D)]
def add(x, y): return tuple(a + b for a, b in zip(x, y))
def sub(x, y): return tuple(a - b for a, b in zip(x, y))
def edge(x, y): return (x, y) if x < y else (y, x)
def nbr_edges(ed):
    out = []
    for v in ed:
        for i in range(D):
            for s in (1, -1):
                w = add(v, E[i]) if s == 1 else sub(v, E[i])
                f = edge(v, w)
                if f != ed: out.append(f)
    return out
O = tuple([0] * D)
origin_edges = sorted(edge(O, add(O, E[i])) for i in range(D)) + sorted(edge(O, sub(O, E[i])) for i in range(D))
origin_edges = sorted(set(origin_edges))
count = Counter()
def is_front(S):
    deg = Counter()
    for (x, y) in S: deg[x] += 1; deg[y] += 1
    return all(c >= 2 for c in deg.values())
def redelmeier(root, forbidden_root):
    # standard Redelmeier: untried set, polyomino-style on the graph of edges (adjacent = share a vertex)
    import itertools
    sys.setrecursionlimit(10000)
    S = [root]; inS = {root}
    seen = {root} | set(forbidden_root)
    def rec(untried, seen):
        k = len(S)
        if is_front(S):
            oe = [f for f in S if O in f]
            if oe and min(oe) == root: count[k] += 1
        if k == KMAX: return
        untried = list(untried)
        while untried:
            f = untried.pop()
            S.append(f); inS.add(f)
            new = [g for g in nbr_edges(f) if g not in seen]
            seen2 = seen | set(new)
            rec(untried + new, seen2)
            S.pop(); inS.discard(f)
            seen = seen  # f stays forbidden for later branches via 'untried' removal
    nb = [g for g in nbr_edges(root) if g not in seen]
    rec(nb, seen | set(nb))
for idx, e0 in enumerate(origin_edges):
    redelmeier(e0, [])
print(f"D={D}: fronts through the origin by size (k<= {KMAX}): {dict(sorted(count.items()))}")
