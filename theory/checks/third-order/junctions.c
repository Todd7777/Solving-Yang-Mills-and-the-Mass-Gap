/* Section 16 of Part IV: the junction counts of order_counts.py (count_junctions) in C.
 * Usage: junctions D NMAX SIZES [noprune]       e.g. junctions 3 3 4,10     (build: cc -O2 -o junctions junctions.c)
 *
 * Counts, by the number n <= NMAX of plaquettes, the candidate junctions containing p = (bd q, s-1), q the plaquette at the origin in the plane (0,1) of
 * Z^D, with further fronts of exactly the sizes SIZES (a multiset): every link of the junction lies in at least two of its elements (plaquettes and
 * front-pairs; the fronts of one layer are vertex-disjoint), every front shares a vertex with a plaquette, and the markers (link-components of the
 * plaquettes) and the front-pairs form a connected graph under "common vertex" (Definition mg:def:junction, Lemma mg:lem:junction).
 *
 * The search is that of order_counts.py, step for step:
 *  - at a state with a link covered once, take the smallest such link l; branch over the sets T of plaquettes through l (not yet chosen, not
 *    excluded; the others through l are excluded below) and over at most one new front through l in each layer that does not cover l yet;
 *  - at a state with no link covered once ("closed"), remembered in the set `seen` so that it is expanded once: record it if it is a junction (set
 *    `found`), and seed every plaquette at a vertex of the state and every front of a remaining size through such a vertex, each in both layers
 *    when allowed, with the exclusions cleared;
 *  - the capacity prune (a necessary condition: a link covered once needs a later element through it, and the later elements are at most
 *    NMAX - |P| plaquettes of four links and the remaining fronts), applied to the state and to every candidate front, exactly as in order_counts.py.
 * The sets `seen` and `found` store the full canonical key of a state (sorted plaquettes; fronts with their layers and sorted links), so the counts
 * are exact. Fronts are generated by the decision search of fronts_decision.c (every front through the origin once). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static int D, NMAX, R, W, NO, PRUNE = 1;
static long stride[4], NVERT, NLINK, NPLAQ, ORIG;
static int oi[6], oj[6], orient[4][4];
static int rem[64], KF;

/* ---------- fronts through the origin ---------- */
typedef struct { int k, nv; long off; } Front;              /* pool[off..off+k): link offsets (sorted); then nv vertex offsets; relative to the origin */
static Front *FV; static long nFV, capFV;
static int *pool; static long npool, cappool;
#define LO(F, c) ((long)pool[(F)->off + (c)])
#define VO(F, c) ((long)pool[(F)->off + (F)->k + (c)])
static int *FL[4]; static long nFL[4], maxFL;
static int *FVk[64]; static long nFVk[64];          /* the fronts through the origin by size */
static int *FLk[4][64]; static long nFLk[4][64];    /* those containing the link (O, i), by size */
static int want[64];

static char *eS, *eX, *eDec; static unsigned char *eDeg; static long *eAct; static char *eIsAct; static int eNact, eNS;
static inline int incid(long v, long *L, long *O) {
    int c = 0;
    for (int i = 0; i < D; i++) { L[c] = v * D + i; O[c] = v + stride[i]; c++; L[c] = (v - stride[i]) * D + i; O[c] = v - stride[i]; c++; }
    return c;
}
static int cmpl(const void *a, const void *b) { long x = *(const long *)a, y = *(const long *)b; return (x > y) - (x < y); }
static void store_front(void) {
    long links[64]; int k = 0;
    long verts[64]; int nv = 0;
    for (int a = 0; a < eNact; a++) {
        long v = eAct[a];
        verts[nv++] = v - ORIG;
        for (int i = 0; i < D; i++) { long L = v * D + i; if (eS[L]) links[k++] = L - ORIG * D; }
    }
    qsort(links, k, sizeof(long), cmpl);
    if (nFV == capFV) { capFV = capFV ? 2 * capFV : 1024; FV = realloc(FV, capFV * sizeof(Front)); }
    if (npool + k + nv > cappool) { cappool = cappool ? 2 * cappool : 1 << 20; pool = realloc(pool, cappool * sizeof(int)); }
    if (!FV || !pool) { fprintf(stderr, "out of memory (fronts)\n"); exit(1); }
    Front *F = &FV[nFV++];
    F->k = k; F->nv = nv; F->off = npool;
    for (int a = 0; a < k; a++) pool[npool++] = (int)links[a];
    for (int a = 0; a < nv; a++) pool[npool++] = (int)verts[a];
}
static void erec(long v) {
    long L[16], O[16], U[16], UO[16]; int nu = 0;
    int m = incid(v, L, O);
    for (int j = 0; j < m; j++) if (!eS[L[j]] && !eX[L[j]]) { U[nu] = L[j]; UO[nu] = O[j]; nu++; }
    for (int mask = 0; mask < (1 << nu); mask++) {
        int r = __builtin_popcount(mask);
        if (eNS + r > KF || eDeg[v] + r < 2) continue;
        int nact0 = eNact;
        for (int j = 0; j < nu; j++) {
            if (mask >> j & 1) {
                eS[U[j]] = 1; long w = UO[j]; eDeg[v]++; eDeg[w]++;
                if (!eIsAct[w]) { eIsAct[w] = 1; eAct[eNact++] = w; }
            } else eX[U[j]] = 1;
        }
        if (!eIsAct[v]) { eIsAct[v] = 1; eAct[eNact++] = v; }
        eDec[v] = 1; eNS += r;
        long best = -1; int bk1 = 0, bk2 = 0, ones = 0;
        for (int a = 0; a < eNact; a++) {
            long w = eAct[a]; if (eDec[w]) continue;
            if (eDeg[w] == 1) ones++;
            int k1 = eDeg[w] == 1 ? 0 : 1, k2 = 0; long L2[16], O2[16]; int m2 = incid(w, L2, O2);
            for (int j = 0; j < m2; j++) if (!eS[L2[j]] && !eX[L2[j]]) k2++;
            if (best < 0 || k1 < bk1 || (k1 == bk1 && (k2 < bk2 || (k2 == bk2 && w < best)))) { best = w; bk1 = k1; bk2 = k2; }
        }
        if (best < 0) { if (want[eNS]) store_front(); }
        else if (eNS + (ones + 1) / 2 <= KF) erec(best);
        eNS -= r; eDec[v] = 0;
        for (int j = 0; j < nu; j++) { if (mask >> j & 1) { eS[U[j]] = 0; eDeg[v]--; eDeg[UO[j]]--; } else eX[U[j]] = 0; }
        while (eNact > nact0) { eNact--; eIsAct[eAct[eNact]] = 0; }
    }
}

/* ---------- canonical keys and exact hash sets ---------- */
typedef struct { uint64_t h; long *key; } Slot;
typedef struct { Slot *s; long cap, n; } Set;
static uint64_t hkey(const long *k, long len) {
    uint64_t h = 1469598103934665603ULL;
    for (long i = 0; i < len; i++) { h ^= (uint64_t)k[i] + 0x9e3779b97f4a7c15ULL + (h << 6) + (h >> 2); h *= 1099511628211ULL; }
    return h ? h : 1;
}
static int set_insert(Set *S, const long *k, long len) {   /* 1 if new */
    if (2 * (S->n + 1) > S->cap) {
        long nc = S->cap ? 2 * S->cap : 1 << 16; Slot *ns = calloc(nc, sizeof(Slot));
        for (long i = 0; i < S->cap; i++) if (S->s[i].h) { long j = S->s[i].h & (nc - 1); while (ns[j].h) j = (j + 1) & (nc - 1); ns[j] = S->s[i]; }
        free(S->s); S->s = ns; S->cap = nc;
    }
    uint64_t h = hkey(k, len); long j = h & (S->cap - 1);
    while (S->s[j].h) {
        if (S->s[j].h == h && S->s[j].key[0] == len && memcmp(S->s[j].key + 1, k, len * sizeof(long)) == 0) return 0;
        j = (j + 1) & (S->cap - 1);
    }
    S->s[j].h = h; S->s[j].key = malloc((len + 1) * sizeof(long)); S->s[j].key[0] = len; memcpy(S->s[j].key + 1, k, len * sizeof(long));
    S->n++; return 1;
}
static Set seen, found;
static long long count_n[64];

/* ---------- the state ---------- */
static unsigned char *cnt; static long *tl; static long ntl;
static char *inP, *exP; static long Plist[64]; static int nP;
static long exstack[4096]; static int nex;
typedef struct { long f, b; int lam; } FP;               /* front f of FV translated to base vertex b, layer lam (0 = s-1, 1 = s) */
static FP Flist[64]; static int nF;                          /* Flist[0] is p0 */
static char *occV[2], *flk[2];

static inline void plinks(long P, long *L) {
    long v = P / NO; int o = P % NO, i = oi[o], j = oj[o];
    L[0] = v * D + i; L[1] = (v + stride[i]) * D + j; L[2] = (v + stride[j]) * D + i; L[3] = v * D + j;
}
static inline void pverts(long P, long *V) {
    long v = P / NO; int o = P % NO, i = oi[o], j = oj[o];
    V[0] = v; V[1] = v + stride[i]; V[2] = v + stride[j]; V[3] = v + stride[i] + stride[j];
}
static inline void inc_link(long L) { if (cnt[L]++ == 0) tl[ntl++] = L; }
static inline void dec_link(long L) { if (--cnt[L] == 0) { ntl--; if (tl[ntl] != L) { fprintf(stderr, "undo order\n"); exit(2); } } }
static void add_plaq(long P) { long L[4]; plinks(P, L); for (int a = 0; a < 4; a++) inc_link(L[a]); inP[P] = 1; Plist[nP++] = P; }
static void del_plaq(long P) { long L[4]; plinks(P, L); for (int a = 3; a >= 0; a--) dec_link(L[a]); inP[P] = 0; nP--; }
static void add_front(long f, long b, int lam) {
    Front *F = &FV[f];
    for (int a = 0; a < F->k; a++) { long L = b * D + LO(F, a); inc_link(L); flk[lam][L] = 1; }
    for (int a = 0; a < F->nv; a++) occV[lam][b + VO(F, a)] = 1;
    rem[F->k]--; Flist[nF].f = f; Flist[nF].b = b; Flist[nF].lam = lam; nF++;
}
static void del_front(void) {
    nF--; long f = Flist[nF].f, b = Flist[nF].b; int lam = Flist[nF].lam; Front *F = &FV[f];
    for (int a = 0; a < F->nv; a++) occV[lam][b + VO(F, a)] = 0;
    for (int a = F->k - 1; a >= 0; a--) { long L = b * D + LO(F, a); flk[lam][L] = 0; dec_link(L); }
    rem[F->k]++;
}
static inline int can_add(long f, long b, int lam) {
    Front *F = &FV[f];
    for (int a = 0; a < F->nv; a++) if (occV[lam][b + VO(F, a)]) return 0;
    return 1;
}
static int remsum(void) { int s = 0; for (int k = 0; k < 64; k++) if (rem[k] > 0) s += rem[k]; return s; }
static int capacity(void) { int c = 4 * (NMAX - nP); for (int k = 0; k < 64; k++) if (rem[k] > 0) c += k * rem[k]; return c; }

/* canonical key of the state: [nP, sorted plaquettes, nF, then for each front sorted by (first link, layer): layer, size, links...] */
static long keybuf[8192]; static long keylen;
typedef struct { long first; int lam; int idx; } FK;
static int cmpfk(const void *a, const void *b) {
    const FK *x = a, *y = b; if (x->first != y->first) return (x->first > y->first) - (x->first < y->first); return x->lam - y->lam;
}
static void make_key(void) {
    long ps[64]; for (int a = 0; a < nP; a++) ps[a] = Plist[a];
    qsort(ps, nP, sizeof(long), cmpl);
    keylen = 0; keybuf[keylen++] = nP; for (int a = 0; a < nP; a++) keybuf[keylen++] = ps[a];
    FK fk[64]; for (int a = 0; a < nF; a++) { fk[a].first = Flist[a].b * D + LO(&FV[Flist[a].f], 0); fk[a].lam = Flist[a].lam; fk[a].idx = a; }
    qsort(fk, nF, sizeof(FK), cmpfk);
    keybuf[keylen++] = nF;
    for (int a = 0; a < nF; a++) {
        FP *e = &Flist[fk[a].idx]; Front *F = &FV[e->f];
        keybuf[keylen++] = e->lam; keybuf[keylen++] = F->k;
        for (int c = 0; c < F->k; c++) keybuf[keylen++] = e->b * D + LO(F, c);
    }
}

/* the junction conditions at a closed state */
static long *stamp; static long stampc;
static void finish(void) {
    if (remsum() != 0 || nP == 0) return;
    /* every front shares a vertex with a plaquette */
    stampc++;
    for (int a = 0; a < nP; a++) { long V[4]; pverts(Plist[a], V); for (int c = 0; c < 4; c++) stamp[V[c]] = stampc; }
    for (int a = 0; a < nF; a++) {
        Front *F = &FV[Flist[a].f]; int ok = 0;
        for (int c = 0; c < F->nv; c++) if (stamp[Flist[a].b + VO(F, c)] == stampc) { ok = 1; break; }
        if (!ok) return;
    }
    /* connectivity: union-find over plaquettes (sharing a link) and fronts, then nodes sharing a vertex */
    int N = nP + nF, par[128];
    for (int a = 0; a < N; a++) par[a] = a;
    #define FIND(x) ({ int _x = (x); while (par[_x] != _x) { par[_x] = par[par[_x]]; _x = par[_x]; } _x; })
    for (int a = 0; a < nP; a++) for (int c = a + 1; c < nP; c++) {
        long La[4], Lc[4]; plinks(Plist[a], La); plinks(Plist[c], Lc); int sh = 0;
        for (int x = 0; x < 4 && !sh; x++) for (int y = 0; y < 4; y++) if (La[x] == Lc[y]) { sh = 1; break; }
        if (sh) par[FIND(a)] = FIND(c);
    }
    /* vertex sets of the nodes: markers (unions of their plaquettes) and fronts; join nodes with a common vertex */
    for (int a = 0; a < N; a++) for (int c = a + 1; c < N; c++) {
        if (FIND(a) == FIND(c)) continue;
        /* do element a and element c share a vertex? (markers are unions of plaquettes, so element-wise sharing suffices) */
        long Va[64], Vc[64]; int na = 0, nc = 0;
        if (a < nP) { pverts(Plist[a], Va); na = 4; } else { Front *F = &FV[Flist[a - nP].f]; for (int x = 0; x < F->nv; x++) Va[na++] = Flist[a - nP].b + VO(F, x); }
        if (c < nP) { pverts(Plist[c], Vc); nc = 4; } else { Front *F = &FV[Flist[c - nP].f]; for (int x = 0; x < F->nv; x++) Vc[nc++] = Flist[c - nP].b + VO(F, x); }
        int sh = 0;
        for (int x = 0; x < na && !sh; x++) for (int y = 0; y < nc; y++) if (Va[x] == Vc[y]) { sh = 1; break; }
        if (sh) par[FIND(a)] = FIND(c);
    }
    int r0 = FIND(0);
    for (int a = 1; a < N; a++) if (FIND(a) != r0) return;
    #undef FIND
    make_key();
    if (set_insert(&found, keybuf, keylen)) count_n[nP]++;
}

static long nodes;
static long *vstamp; static long vstampc;
static void rec(void);
static void clear_excl_and_rec(void) {
    int save = nex; long saved[4096];
    memcpy(saved, exstack, nex * sizeof(long));
    for (int a = 0; a < nex; a++) exP[exstack[a]] = 0;
    nex = 0;
    rec();
    nex = save; memcpy(exstack, saved, save * sizeof(long));
    for (int a = 0; a < nex; a++) exP[exstack[a]] = 1;
}
static void rec(void) {
    nodes++;
    /* links covered once */
    long ndef = 0, lmin = -1;
    for (long a = 0; a < ntl; a++) if (cnt[tl[a]] == 1) { ndef++; if (lmin < 0 || tl[a] < lmin) lmin = tl[a]; }
    int capf = capacity();
    if (PRUNE && ndef > capf) return;
    int rs = remsum();
    if (ndef == 0) {
        make_key();
        if (!set_insert(&seen, keybuf, keylen)) return;
        finish();
        /* the vertices of the state */
        vstampc++;
        long V[4096]; int nV = 0;
        for (int a = 0; a < nP; a++) { long PV[4]; pverts(Plist[a], PV); for (int c = 0; c < 4; c++) if (vstamp[PV[c]] != vstampc) { vstamp[PV[c]] = vstampc; V[nV++] = PV[c]; } }
        for (int a = 0; a < nF; a++) { Front *F = &FV[Flist[a].f]; for (int c = 0; c < F->nv; c++) { long u = Flist[a].b + VO(F, c); if (vstamp[u] != vstampc) { vstamp[u] = vstampc; V[nV++] = u; } } }
        long myV = vstampc;
        /* seeds: plaquettes at a vertex (each once), fronts through a vertex (each at its smallest vertex in V) */
        long seedP[4096]; int nsp = 0;
        if (nP < NMAX) {
            stampc++;
            for (int a = 0; a < nV; a++) {
                long v = V[a];
                for (int o = 0; o < NO; o++) for (int si = 0; si < 2; si++) for (int sj = 0; sj < 2; sj++) {
                    long x = v - si * stride[oi[o]] - sj * stride[oj[o]]; long P = x * NO + o;
                    if (!inP[P] && stamp[P] != stampc) { stamp[P] = stampc; seedP[nsp++] = P; }
                }
            }
        }
        for (int a = 0; a < nsp; a++) { add_plaq(seedP[a]); clear_excl_and_rec(); del_plaq(seedP[a]); }
        if (rs > 0) {
            for (int a = 0; a < nV; a++) {
                long v = V[a];
                vstampc++; myV = vstampc; for (int c = 0; c < nV; c++) vstamp[V[c]] = myV;     /* V again (the recursion re-stamps vertices) */
                for (int k = 4; k < 64; k++) {
                  if (rem[k] <= 0 || !nFVk[k]) continue;
                  /* a front of size k has at least k - |U| links outside U: if that exceeds capf - k, the prune rejects every front of this size */
                  if (PRUNE && k - ntl > capf - k) continue;
                  for (long t = 0; t < nFVk[k]; t++) {
                    long f = FVk[k][t];
                    Front *F = &FV[f];
                    /* the same front through several vertices of V: take it at the smallest one */
                    int skip = 0;
                    for (int c = 0; c < F->nv; c++) { long u = v + VO(F, c); if (u < v && vstamp[u] == myV) { skip = 1; break; } }
                    if (skip) continue;
                    if (PRUNE) { int newl = 0; for (int c = 0; c < F->k; c++) if (cnt[v * D + LO(F, c)] == 0) newl++; if (newl > capf - F->k) continue; }
                    for (int lam = 0; lam < 2; lam++) {
                        if (!can_add(f, v, lam)) continue;
                        add_front(f, v, lam); clear_excl_and_rec(); del_front();
                    }
                  }
                }
            }
        }
        return;
    }
    long l = lmin; long base = l / D; int dir = l % D;
    /* real candidates through l */
    long creal[8]; int ncr = 0;
    for (int m = 0; m < D; m++) {
        if (m == dir) continue;
        int i = dir < m ? dir : m, j = dir < m ? m : dir, o = orient[i][j];
        long P1 = base * NO + o, P2 = (base - stride[m]) * NO + o;
        if (!inP[P1] && !exP[P1]) creal[ncr++] = P1;
        if (!inP[P2] && !exP[P2]) creal[ncr++] = P2;
    }
    /* front candidates through l */
    static int *cf_f[64]; static char *cf_l[64]; static int depth = 0;
    if (!cf_f[depth]) { cf_f[depth] = malloc(sizeof(int) * (2 * maxFL + 2)); cf_l[depth] = malloc(2 * maxFL + 2); if (!cf_f[depth] || !cf_l[depth]) { fprintf(stderr, "out of memory (candidates)\n"); exit(1); } }
    int *cff = cf_f[depth]; char *cfl = cf_l[depth]; long ncf = 0;
    if (rs > 0) {
        int ndl = 0; stampc++;
        for (long a = 0; a < ntl; a++) if (cnt[tl[a]] == 1) { stamp[tl[a]] = stampc; ndl++; }
        long dmk = stampc;
        for (int lam = 0; lam < 2; lam++) {
            if (flk[lam][l]) continue;
            for (int k = 4; k < 64; k++) {
              if (rem[k] <= 0 || !nFLk[dir][k]) continue;
              /* at best H covers min(k, |D1|) links of D1 and has max(0, k - |U|) links outside U */
              if (PRUNE && ndl - (k < ndl ? k : ndl) + (k > ntl ? k - ntl : 0) > capf - k) continue;
              for (long t = 0; t < nFLk[dir][k]; t++) {
                long f = FLk[dir][k][t]; Front *F = &FV[f];
                if (PRUNE) {
                    int inD = 0, newl = 0;
                    for (int c = 0; c < F->k; c++) { long L = base * D + LO(F, c); if (cnt[L] == 0) newl++; else if (stamp[L] == dmk) inD++; }
                    if (ndl - inD + newl > capf - F->k) continue;
                }
                if (!can_add(f, base, lam)) continue;
                cff[ncf] = (int)f; cfl[ncf] = (char)lam; ncf++;
              }
            }
        }
    }
    int room = NMAX - nP;
    depth++;
    for (int mask = 0; mask < (1 << ncr); mask++) {
        int r = __builtin_popcount(mask);
        if (r > room) continue;
        for (int a = 0; a < ncr; a++) if (mask >> a & 1) add_plaq(creal[a]);
        int nex0 = nex;
        for (int a = 0; a < ncr; a++) if (!(mask >> a & 1)) { exP[creal[a]] = 1; exstack[nex++] = creal[a]; }
        /* front options: none, one, or two in different layers */
        if (r > 0) rec();
        for (long x = 0; x < ncf; x++) {
            add_front(cff[x], base, cfl[x]);
            rec();
            for (long y = x + 1; y < ncf; y++) {
                if (cfl[y] == cfl[x]) continue;
                if (rem[FV[cff[y]].k] <= 0) continue;
                add_front(cff[y], base, cfl[y]);
                rec();
                del_front();
            }
            del_front();
        }
        while (nex > nex0) { nex--; exP[exstack[nex]] = 0; }
        for (int a = ncr - 1; a >= 0; a--) if (mask >> a & 1) del_plaq(creal[a]);
    }
    depth--;
}

int main(int argc, char **argv) {
    if (argc < 4) { fprintf(stderr, "usage: %s D NMAX SIZES [noprune]\n", argv[0]); return 1; }
    D = atoi(argv[1]); NMAX = atoi(argv[2]);
    int sizes[32], ns = 0, ssum = 0; KF = 0;
    char sizes_arg[256]; snprintf(sizes_arg, sizeof sizes_arg, "%s", argv[3]);
    for (char *t = strtok(argv[3], ","); t; t = strtok(NULL, ",")) { sizes[ns] = atoi(t); rem[sizes[ns]]++; want[sizes[ns]] = 1; ssum += sizes[ns]; if (sizes[ns] > KF) KF = sizes[ns]; ns++; }
    if (argc > 4 && strcmp(argv[4], "noprune") == 0) PRUNE = 0;
    NO = 0; for (int i = 0; i < D; i++) for (int j = i + 1; j < D; j++) { oi[NO] = i; oj[NO] = j; orient[i][j] = NO; NO++; }
    R = 6 + 2 * NMAX + ssum + KF; W = 2 * R + 1;
    NVERT = 1; for (int i = 0; i < D; i++) { stride[i] = NVERT; NVERT *= W; }
    NLINK = NVERT * D; NPLAQ = NVERT * NO;
    ORIG = 0; for (int i = 0; i < D; i++) ORIG += (long)R * stride[i];
    /* fronts through the origin of the sizes needed */
    eS = calloc(NLINK, 1); eX = calloc(NLINK, 1); eDec = calloc(NVERT, 1); eDeg = calloc(NVERT, 1); eIsAct = calloc(NVERT, 1);
    eAct = malloc(sizeof(long) * (KF + 8) * 4);
    eNact = 0; eNS = 0; erec(ORIG);
    free(eS); free(eX); free(eDec); free(eDeg); free(eIsAct); free(eAct);
    for (int i = 0; i < D; i++) { FL[i] = malloc(sizeof(int) * (nFV + 1)); nFL[i] = 0; }
    for (long f = 0; f < nFV; f++) for (int i = 0; i < D; i++) {
        long L0 = (long)0 * D + i; int has = 0;            /* the link (O, i) has offset i */
        for (int c = 0; c < FV[f].k; c++) if (LO(&FV[f], c) == L0) { has = 1; break; }
        if (has) FL[i][nFL[i]++] = (int)f;
    }
    maxFL = 0; for (int i = 0; i < D; i++) if (nFL[i] > maxFL) maxFL = nFL[i];
    for (long f = 0; f < nFV; f++) { int k = FV[f].k; if (!FVk[k]) FVk[k] = malloc(sizeof(int) * (nFV + 1)); FVk[k][nFVk[k]++] = (int)f; }
    for (int i = 0; i < D; i++) for (long t = 0; t < nFL[i]; t++) { int f = FL[i][t], k = FV[f].k; if (!FLk[i][k]) FLk[i][k] = malloc(sizeof(int) * (nFL[i] + 1)); FLk[i][k][nFLk[i][k]++] = f; }
    fprintf(stderr, "D=%d NMAX=%d sizes=%s: %ld fronts through the origin; through (O,i):", D, NMAX, sizes_arg, nFV);
    for (int i = 0; i < D; i++) fprintf(stderr, " %ld", nFL[i]);
    fprintf(stderr, "\n");
    /* the state */
    cnt = calloc(NLINK, 1); tl = malloc(sizeof(long) * 100000); inP = calloc(NPLAQ, 1); exP = calloc(NPLAQ, 1);
    occV[0] = calloc(NVERT, 1); occV[1] = calloc(NVERT, 1); flk[0] = calloc(NLINK, 1); flk[1] = calloc(NLINK, 1);
    stamp = calloc(NPLAQ > NLINK ? NPLAQ : NLINK, sizeof(long)); vstamp = calloc(NVERT, sizeof(long));
    if (!cnt || !inP || !exP || !occV[0] || !occV[1] || !flk[0] || !flk[1] || !stamp || !vstamp) { fprintf(stderr, "out of memory\n"); return 1; }
    /* p0 = (bd q, s-1), q = (O, 0, 1): a front of layer 0 with the four links of q; it is stored as an extra front class */
    long q = ORIG * NO + orient[0][1]; long QL[4], QV[4]; plinks(q, QL); pverts(q, QV);
    if (nFV == capFV) { capFV = capFV ? 2 * capFV : 1024; FV = realloc(FV, capFV * sizeof(Front)); }
    if (npool + 8 > cappool) { cappool = cappool ? 2 * cappool : 1 << 20; pool = realloc(pool, cappool * sizeof(int)); }
    long ql[4]; for (int a = 0; a < 4; a++) ql[a] = QL[a] - ORIG * D;
    qsort(ql, 4, sizeof(long), cmpl);
    Front *F0 = &FV[nFV]; F0->k = 4; F0->nv = 4; F0->off = npool;
    for (int a = 0; a < 4; a++) pool[npool++] = (int)ql[a];
    for (int a = 0; a < 4; a++) pool[npool++] = (int)(QV[a] - ORIG);
    long f0 = nFV; nFV++;                                   /* not in FL, and seeds never use it: rem[4] counts only the further fronts */
    rem[4]++; add_front(f0, ORIG, 0);                        /* add_front decrements rem[4]; p0 is not a further front */
    long nFVseed = nFV - 1; long nFVsave = nFV; nFV = nFVseed; /* seeds and candidates range over the true fronts only */
    (void)nFVsave;
    /* make FV[f0] reachable for keys and finish (they index Flist[].f directly), while loops over fronts stop before it */
    rec();
    printf("D=%d NMAX=%d sizes=%s%s: junctions by n:", D, NMAX, sizes_arg, PRUNE ? "" : " (no prune)");
    for (int n = 0; n <= NMAX; n++) if (count_n[n]) printf(" %d:%lld", n, count_n[n]);
    printf("\n  closed states %ld, nodes %ld\n", seen.n, nodes);
    return 0;
}
