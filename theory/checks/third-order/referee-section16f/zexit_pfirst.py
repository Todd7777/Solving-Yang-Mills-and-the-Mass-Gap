# Referee (Section 16, sixth pass): Z_(n,k), the junctions with exactly two front-pairs p = (bd q, s-1) and p' (|p'| = k >= 5), and n plaquettes,
# counted from the definitions, plaquettes first.   Usage: python3 zexit_pfirst.py D NMAX
"""Facts used (each follows from Definition mg:def:junction and Lemma mg:lem:junction(iii) directly):
 (a) every link e of the front phi' of p' has n_J(e) >= 2, so it lies in bd q (if p' is in the other layer) or in a plaquette of P:
     phi' is contained in G := bd q u E(P);
 (b) hence V(phi') is contained in V(q) u V(P), and H_s minus p' is still connected (walk along phi': consecutive links lie in p or in markers
     sharing their common vertex); so the vertex sets of q and of the plaquettes of P form a connected family;
 (c) n_J(e) = [e in bd q] + [e in phi'] + pi(e) >= 2 on G (both layers: if p' has the layer of p, bd q and phi' are disjoint), so phi' contains
     Def(P) := {e in G : [e in bd q] + pi(e) = 1}: phi' = Def(P) u T with T a subset of the links of G with [e in bd q] + pi(e) >= 2.
Enumeration: all sets P of n plaquettes such that {q} u P is connected by common vertices (generated by adding plaquettes at vertices of the
current family, each set once); for each, every T, both layers; then every condition is checked from scratch: phi' a front (connected, all degrees
>= 2), |phi'| = k >= 5, n_J >= 2 on E(J), the fronts of one layer vertex-disjoint, every front touching P, H_s connected (markers = link-components
of P; adjacency = common vertex).  Pairs (J, p') are counted once each, by (n, k, layer of p' relative to p).  Different from zexit_count_n.py: no
decision search for fronts; phi' is Def(P) plus a subset of the doubly covered links, and both layers are tried."""
import sys, itertools
from collections import Counter

D = int(sys.argv[1]); NMAX = int(sys.argv[2])
E = [tuple(1 if k == i else 0 for k in range(D)) for i in range(D)]
add = lambda x, y: tuple(a + b for a, b in zip(x, y))
sub = lambda x, y: tuple(a - b for a, b in zip(x, y))
ends = lambda l: (l[0], add(l[0], E[l[1]]))
def plinks(c):
    x, i, j = c
    return ((x, i), (add(x, E[i]), j), (add(x, E[j]), i), (x, j))
def pverts(c):
    x, i, j = c
    return (x, add(x, E[i]), add(x, E[j]), add(add(x, E[i]), E[j]))
def plaqs_at(v):
    out = []
    for i, j in itertools.combinations(range(D), 2):
        for a in (0, 1):
            for b in (0, 1):
                y = v
                if a: y = sub(y, E[i])
                if b: y = sub(y, E[j])
                out.append((y, i, j))
    return out
O = (0,) * D
q = (O, 0, 1); dq = frozenset(plinks(q)); Vq = frozenset(pverts(q))

def is_front(S):
    deg = Counter()
    for l in S:
        for v in ends(l): deg[v] += 1
    if any(c < 2 for c in deg.values()): return False
    # connected
    S = list(S); adj = {}
    for l in S:
        for v in ends(l): adj.setdefault(v, []).append(l)
    seen = {S[0]}; stack = [S[0]]
    while stack:
        l = stack.pop()
        for v in ends(l):
            for m in adj[v]:
                if m not in seen: seen.add(m); stack.append(m)
    return len(seen) == len(S)

def connected_nodes(nodes):
    par = list(range(len(nodes)))
    def f(a):
        while par[a] != a: a = par[a]
        return a
    for a, b in itertools.combinations(range(len(nodes)), 2):
        if nodes[a] & nodes[b]: par[f(a)] = f(b)
    return len({f(a) for a in range(len(nodes))}) == 1

def check(P, phi, lay):
    """all conditions from scratch; lay = 0: the layer of p, 1: the other"""
    A = set(dq) | (set(phi) if lay == 0 else set()); B = set(phi) if lay == 1 else set()
    pi = Counter(l for c in P for l in plinks(c))
    EJ = A | B | set(pi)
    if any((l in A) + (l in B) + pi[l] < 2 for l in EJ): return False
    Vphi = frozenset(v for l in phi for v in ends(l))
    if lay == 0 and (Vphi & Vq): return False
    VP = set(v for c in P for v in pverts(c))
    if not (Vq & VP) or not (Vphi & VP): return False
    Pl = list(P); par = list(range(len(Pl)))
    def f(a):
        while par[a] != a: a = par[a]
        return a
    for a, b in itertools.combinations(range(len(Pl)), 2):
        if set(plinks(Pl[a])) & set(plinks(Pl[b])): par[f(a)] = f(b)
    mk = {}
    for a in range(len(Pl)): mk.setdefault(f(a), set()).update(pverts(Pl[a]))
    return connected_nodes([frozenset(m) for m in mk.values()] + [Vq, Vphi])

def sets_P(nmax):
    """all sets of n <= nmax plaquettes P such that {q} u P is connected by common vertices (q itself may be in P)"""
    level = set()
    for v in Vq:
        for c in plaqs_at(v): level.add(frozenset([c]))
    out = list(level)
    for n in range(2, nmax + 1):
        nxt = set()
        for S in level:
            V = set(Vq)
            for c in S: V.update(pverts(c))
            for v in V:
                for c in plaqs_at(v):
                    if c not in S: nxt.add(S | {c})
        out.extend(nxt); level = nxt
    return out

found = Counter(); nP = Counter()
for P in sets_P(NMAX):
    n = len(P); nP[n] += 1
    pi = Counter(l for c in P for l in plinks(c))
    G = set(dq) | set(pi)
    cnt = {l: (l in dq) + pi[l] for l in G}
    Def = [l for l in G if cnt[l] == 1]; Rest = sorted(l for l in G if cnt[l] >= 2)
    for r in range(len(Rest) + 1):
        for T in itertools.combinations(Rest, r):
            phi = frozenset(Def) | frozenset(T)
            if len(phi) < 5 or not is_front(phi): continue
            for lay in (0, 1):
                if check(P, phi, lay): found[(n, len(phi), lay)] += 1
print(f"D={D}: number of sets P by n: {dict(sorted(nP.items()))}")
for n in range(1, NMAX + 1):
    tot = Counter()
    for (m, k, lay), c in found.items():
        if m == n: tot[k] += c
    print(f"D={D}: Z_({n},k), k >= 5: {dict(sorted(tot.items()))};  same layer as p: {sum(c for (m, k, lay), c in found.items() if m == n and lay == 0)}")
